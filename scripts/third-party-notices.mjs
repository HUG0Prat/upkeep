import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { encoding: 'utf8', shell: true, maxBuffer: 64 * 1024 * 1024 }));
const seen = new Map();
const walk = (deps = {}) => {
  for (const [name, info] of Object.entries(deps)) {
    const key = `${name}@${info.version}`;
    if (!seen.has(key)) {
      seen.set(key, { name, version: info.version });
      walk(info.dependencies);
    }
  }
};
walk(tree.dependencies);

const rows = [];
const texts = [];
for (const { name, version } of [...seen.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const dir = join('node_modules', name);
  if (!existsSync(join(dir, 'package.json'))) continue;
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ') ?? 'INCONNUE';
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  rows.push(`| ${name} | ${version} | ${license || 'INCONNUE'} |`);
  if (file) texts.push(`## ${name} ${version}\n\n\`\`\`\n${readFileSync(join(dir, file), 'utf8').trim()}\n\`\`\`\n`);
}

const allowed = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|CC0-1\.0|Unlicense|Python-2\.0)$/;
const review = rows.filter((r) => !r.split('|')[3].trim().split(/ OR | AND |[()]/).some((l) => allowed.test(l.trim())));

writeFileSync(
  'THIRD_PARTY_NOTICES.md',
  `# Third-party notices\n\nGenerated by \`node scripts/third-party-notices.mjs\` — ${seen.size} packages shipped with UpKeep ` +
    `(production dependencies only). Electron and Chromium add their own license files (LICENSE, LICENSES.chromium.html) to the package.\n\n` +
    `| Package | Version | License |\n|---|---|---|\n${rows.join('\n')}\n\n---\n\n${texts.join('\n')}`,
);
console.log(`${rows.length} paquets ; licences à examiner : ${review.length ? '\n' + review.join('\n') : 'aucune'}`);
